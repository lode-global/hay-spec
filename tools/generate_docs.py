"""Generate deterministic reference documentation; never modify the source YAML."""
import argparse
from datetime import date
import hashlib
import json
from pathlib import Path
import re
import sys

import yaml

try:
    from .validate_spec import inspect_spec, load_spec
except ImportError:
    from validate_spec import inspect_spec, load_spec


CHILDREN = ('fields', 'components', 'groups', 'subsections')
NOTICE = '<!-- Generated by tools/generate_docs.py. Edit src/hay-spec.yaml instead. -->\n'


def reference_label(spec):
    if spec.get('publication_status') == 'published':
        return '**Published specification reference.**'
    return '**Current-source reference, including unreleased additions.**'


def render_node(node, path, depth=2):
    identity = node.get('id', node.get('name', 'unnamed'))
    title = node.get('title', identity)
    anchor = 'node-' + '-'.join(str(part) for part in path)
    # Paths, rather than identifiers, keep duplicate legacy names distinct.
    output = [f'<a id="{anchor}"></a>\n',
              f'{"#" * min(depth, 6)} {title}\n', f'Identifier: `{identity}`\n']
    if 'id' in node and 'name' in node:
        output.append('`name` is a compatibility alias for this same field.\n')
    for key in ('description', 'definition', 'details', 'narration', 'guidance'):
        if key in node:
            output.append(f'**{key.replace("_", " ").title()}**\n\n{node[key]}\n')
    metadata = {k: v for k, v in node.items()
                if k not in CHILDREN and k not in {
                    'id', 'name', 'title', 'description', 'definition',
                    'details', 'narration', 'guidance'}}
    if metadata:
        output.append('```yaml\n' + yaml.safe_dump(
            metadata, sort_keys=False, allow_unicode=True, width=90) + '```\n')
    for key in CHILDREN:
        for i, child in enumerate(node.get(key, [])):
            output.append(render_node(child, [*path, key, i], depth + 1))
    return '\n'.join(output)


def outputs(source):
    spec = load_spec(source)
    findings = inspect_spec(spec)
    if any(f['severity'] == 'error' for f in findings):
        raise ValueError('Resolve specification structure errors before generating docs.')
    for key in ('title', 'version', 'status'):
        if not isinstance(spec.get(key), str) or not spec[key].strip():
            raise ValueError(f'Source {key} must be a nonempty quoted string.')
    if spec.get('publication_status') == 'published':
        published = spec.get('published_on')
        if not isinstance(published, str) or not re.fullmatch(r'\d{4}-\d{2}-\d{2}', published):
            raise ValueError('Published references require a quoted YYYY-MM-DD publication date.')
        date.fromisoformat(published)
    # Do not silently stringify dates, non-string mapping keys, or other YAML
    # values that JSON cannot preserve. Validate before any output is written.
    def json_values(value):
        if isinstance(value, dict):
            if any(not isinstance(key, str) for key in value):
                raise ValueError('JSON transcription requires string mapping keys.')
            for child in value.values():
                json_values(child)
        elif isinstance(value, list):
            for child in value:
                json_values(child)
        elif value is not None and type(value) not in (str, bool, int, float):
            raise ValueError('JSON transcription cannot preserve this YAML scalar type; '
                             'quote date-like values explicitly.')
    json_values(spec)
    transcription = json.dumps(spec, indent=2, ensure_ascii=False, allow_nan=False) + '\n'
    digest = hashlib.sha256(source.encode('utf-8')).hexdigest()
    pages = {}
    links = []
    for i, section in enumerate(spec['sections']):
        identity = section.get('id')
        if not isinstance(identity, str) or not re.fullmatch(r'[a-z][a-z0-9_]*', identity):
            raise ValueError('Section identifiers must be safe documentation filenames.')
        path = f'fields/{identity}.md'
        if path in pages:
            raise ValueError('Duplicate section identifier would overwrite a documentation page.')
        status = (f'> {reference_label(spec)} '
                  f'Source version: {spec["version"]}; status: {spec["status"]}. '
                  '[Overview and source downloads](../index.md).\n\n')
        pages[path] = NOTICE + '\n' + status + render_node(section, ['sections', i], 1)
        links.append(f'- [{section.get("title", identity)}]({path})')
    intro = [NOTICE, f'# {spec["title"]}\n',
             f'Source version: **{spec["version"]}**; status: **{spec["status"]}**.\n',
             (f'Published on {spec["published_on"]}. The specification remains a working draft.\n'
              if spec.get('publication_status') == 'published' else
              'Generated from the current source tree; additions may be unreleased even '
              'when the source still carries the last release version.\n'),
             f'Source SHA-256: `{digest}`\n',
             '[Canonical YAML copy](source/hay-spec.yaml) | '
             '[JSON transcription](source/hay-spec.json)\n',
             'The JSON is a transcription, not a JSON Schema or a hay-record validator. '
             'Arrays, duplicate field identifiers, legacy values, and scalar types are '
             'preserved; YAML comments remain available in the canonical YAML copy.\n',
             '## Interpretation conventions\n',
             '```yaml\n' + yaml.safe_dump({
                 k: spec[k] for k in ('field_naming_conventions', 'field_validation_conventions')
                 if k in spec}, sort_keys=False, allow_unicode=True) + '```\n',
             '## Known source issues\n',
             'These are unresolved source findings, not corrections applied by the generator.\n']
    for finding in findings:
        intro.append(f'- `{finding["code"]}` at `{finding["path"]}`: '
                     f'{finding["message"]}')
    intro += ['\n## Field reference\n', *links]
    # Include all remaining front matter so generation does not lose unknown keys.
    front = {k: v for k, v in spec.items() if k != 'sections'}
    intro += ['\n## Source front matter\n', '```yaml\n' + yaml.safe_dump(
        front, sort_keys=False, allow_unicode=True, width=90) + '```\n']
    pages['index.md'] = '\n'.join(intro)
    pages['source/hay-spec.yaml'] = source
    pages['source/hay-spec.json'] = transcription
    return pages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=Path('src/hay-spec.yaml'))
    parser.add_argument('--output', type=Path, default=Path('docs'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        pages = outputs(args.source.read_text(encoding='utf-8'))
        stale = []
        for name, text in pages.items():
            path = args.output / name
            if args.check:
                if not path.exists() or path.read_text(encoding='utf-8') != text:
                    stale.append(name)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding='utf-8')
        for path in (args.output / 'fields').glob('*.md'):
            if path.relative_to(args.output).as_posix() not in pages:
                stale.append(path.relative_to(args.output).as_posix())
        if stale:
            print('Stale or unexpected generated pages: ' + ', '.join(stale), file=sys.stderr)
            return 1
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f'Documentation generation failed: {exc}', file=sys.stderr)
        return 1
    print(f'{len(pages)} generated files ' + ('verified.' if args.check else 'written.'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
