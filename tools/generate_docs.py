"""Generate deterministic reference documentation; never modify the source YAML."""
import argparse
from datetime import date
import hashlib
import json
from pathlib import Path
import re
import sys

import yaml

try:
    from .validate_spec import inspect_spec, load_spec
    from .field_guides import guide, guide_index, home_page
except ImportError:
    from validate_spec import inspect_spec, load_spec
    from field_guides import guide, guide_index, home_page


CHILDREN = ('fields', 'components', 'groups', 'subsections')
NOTICE = '<!-- Generated by tools/generate_docs.py. Edit src/hay-spec.yaml or reference-display.yaml instead. -->\n'


def reference_label(spec):
    if spec.get('publication_status') == 'published':
        return '**Published specification reference.**'
    return '**Current-source reference, including unreleased additions.**'


def render_node(node, path, depth=2, display=None, scope=None):
    identity = node.get('id', node.get('name', 'unnamed'))
    scope = [*(scope or []), identity]
    display = display or {}
    title = node.get('title', display.get('titles', {}).get('/'.join(scope), identity))
    anchor = 'node-' + '-'.join(str(part) for part in path)
    # Paths, rather than identifiers, keep duplicate legacy names distinct.
    output = [f'<a id="{anchor}"></a>\n',
              f'{"#" * min(depth, 6)} {title}\n', f'Identifier: `{identity}`\n']
    if 'id' in node and 'name' in node:
        output.append('`name` is a compatibility alias for this same field.\n')
    for key in ('description', 'definition', 'details', 'narration', 'guidance'):
        if key in node:
            output.append(f'**{key.replace("_", " ").title()}**\n\n{node[key]}\n')
    metadata = {k: v for k, v in node.items()
                if k not in CHILDREN and k not in {
                    'id', 'name', 'title', 'description', 'definition',
                    'details', 'narration', 'guidance'}}
    if metadata:
        output.append('```yaml\n' + yaml.safe_dump(
            metadata, sort_keys=False, allow_unicode=True, width=90) + '```\n')
    groups = display.get('nutrient_groups', []) if scope == ['nutrient_analysis'] else []
    if groups:
        output.append('## On this page\n\n' + '\n'.join(
            f'- [{g["title"]}](#nav-{g["anchor"]})' for g in groups) + '\n')
    starts = {g['starts_at']: g for g in groups}
    for key in CHILDREN:
        for i, child in enumerate(node.get(key, [])):
            group = starts.get(child.get('id')) if key == 'fields' else None
            # Reuse a source section marker as the navigation heading instead of
            # repeating the same category immediately above it.
            child_scope = '/'.join([*scope, child.get('id', child.get('name', 'unnamed'))])
            child_title = child.get('title', display.get('titles', {}).get(child_scope))
            reuse_heading = (group and child.get('data_type') == 'section'
                             and child_title == group['title'])
            if group and reuse_heading:
                output.append(f'<a id="nav-{group["anchor"]}"></a>\n')
            elif group:
                output.append(f'<a id="nav-{group["anchor"]}"></a>\n\n## {group["title"]}\n')
            output.append(render_node(child, [*path, key, i],
                                      (depth + 1 if reuse_heading else depth + 2)
                                      if groups and key == 'fields' else depth + 1,
                                      display, scope))
    return '\n'.join(output)


def validate_display(spec, display):
    if not isinstance(display, dict) or set(display) != {'titles', 'nutrient_groups'}:
        raise ValueError('Display configuration requires titles and nutrient_groups.')
    nodes = {}
    def walk(node, scope):
        scope = [*scope, node.get('id', node.get('name'))]
        key = '/'.join(scope)
        if key in nodes:
            raise ValueError('Display identities must be unambiguous: ' + key)
        nodes[key] = node
        for child in CHILDREN:
            for item in node.get(child, []):
                walk(item, scope)
    for section in spec['sections']:
        walk(section, [])
    titles = display['titles']
    if not isinstance(titles, dict):
        raise ValueError('Display titles must be a mapping.')
    for key, title in titles.items():
        if key not in nodes or 'title' in nodes[key]:
            raise ValueError('Display title is stale or overrides an existing source title: ' + str(key))
        if not isinstance(title, str) or not title.strip() or '\n' in title:
            raise ValueError('Display titles must be nonempty single-line strings.')
    groups = display['nutrient_groups']
    if not isinstance(groups, list):
        raise ValueError('Nutrient navigation groups must be a list.')
    fields = next((s['fields'] for s in spec['sections'] if s['id'] == 'nutrient_analysis'), [])
    ids = [f['id'] for f in fields]
    seen = set()
    previous = -1
    for group in groups:
        if not isinstance(group, dict) or set(group) != {'anchor', 'title', 'starts_at'}:
            raise ValueError('Each navigation group requires anchor, title, and starts_at.')
        anchor, title, start = group['anchor'], group['title'], group['starts_at']
        if (not isinstance(anchor, str) or not re.fullmatch(r'[a-z][a-z0-9-]*', anchor)
                or anchor in seen or not isinstance(title, str) or not title.strip()
                or '\n' in title or start not in ids):
            raise ValueError('Invalid or stale nutrient navigation group.')
        position = ids.index(start)
        if position <= previous or (previous == -1 and position != 0):
            raise ValueError('Navigation groups must start at the first field and follow source order.')
        seen.add(anchor)
        previous = position


def outputs(source, display=None):
    spec = load_spec(source)
    findings = inspect_spec(spec)
    if any(f['severity'] == 'error' for f in findings):
        raise ValueError('Resolve specification structure errors before generating docs.')
    for key in ('title', 'version', 'status'):
        if not isinstance(spec.get(key), str) or not spec[key].strip():
            raise ValueError(f'Source {key} must be a nonempty quoted string.')
    if spec.get('publication_status') == 'published':
        published = spec.get('published_on')
        if not isinstance(published, str) or not re.fullmatch(r'\d{4}-\d{2}-\d{2}', published):
            raise ValueError('Published references require a quoted YYYY-MM-DD publication date.')
        date.fromisoformat(published)
    # Do not silently stringify dates, non-string mapping keys, or other YAML
    # values that JSON cannot preserve. Validate before any output is written.
    def json_values(value):
        if isinstance(value, dict):
            if any(not isinstance(key, str) for key in value):
                raise ValueError('JSON transcription requires string mapping keys.')
            for child in value.values():
                json_values(child)
        elif isinstance(value, list):
            for child in value:
                json_values(child)
        elif value is not None and type(value) not in (str, bool, int, float):
            raise ValueError('JSON transcription cannot preserve this YAML scalar type; '
                             'quote date-like values explicitly.')
    json_values(spec)
    if display is not None:
        validate_display(spec, display)
    transcription = json.dumps(spec, indent=2, ensure_ascii=False, allow_nan=False) + '\n'
    digest = hashlib.sha256(source.encode('utf-8')).hexdigest()
    pages = {}
    links = []
    for i, section in enumerate(spec['sections']):
        identity = section.get('id')
        if not isinstance(identity, str) or not re.fullmatch(r'[a-z][a-z0-9_]*', identity):
            raise ValueError('Section identifiers must be safe documentation filenames.')
        path = f'fields/{identity}.md'
        if path in pages:
            raise ValueError('Duplicate section identifier would overwrite a documentation page.')
        status = (f'> {reference_label(spec)} '
                  f'Source version: {spec["version"]}; status: {spec["status"]}. '
                  '[Overview and source downloads](../index.md).\n\n')
        pages[path] = NOTICE + '\n' + status + render_node(section, ['sections', i], 1, display)
        links.append(f'- [{section.get("title", identity)}]({path})')
    intro = [NOTICE, f'# {spec["title"]}\n',
             f'Source version: **{spec["version"]}**; status: **{spec["status"]}**.\n',
             (f'Published on {spec["published_on"]}. The specification remains a working draft.\n'
              if spec.get('publication_status') == 'published' else
              'Generated from the current source tree; additions may be unreleased even '
              'when the source still carries the last release version.\n'),
             f'Source SHA-256: `{digest}`\n',
             '[Canonical YAML copy](source/hay-spec.yaml) | '
             '[JSON transcription](source/hay-spec.json)\n',
             'The JSON is a transcription, not a JSON Schema or a hay-record validator. '
             'Arrays, duplicate field identifiers, legacy values, and scalar types are '
             'preserved; YAML comments remain available in the canonical YAML copy.\n',
             '## Interpretation conventions\n',
             '```yaml\n' + yaml.safe_dump({
                 k: spec[k] for k in ('field_naming_conventions', 'field_validation_conventions')
                 if k in spec}, sort_keys=False, allow_unicode=True) + '```\n',
             '## Known source issues\n',
             'These are unresolved source findings, not corrections applied by the generator.\n']
    for finding in findings:
        intro.append(f'- `{finding["code"]}` at `{finding["path"]}`: '
                     f'{finding["message"]}')
    if display is not None:
        intro.append('\nDisplay titles and nutrient navigation are presentation-only; '
                     'the source downloads and record identifiers are unchanged.\n')
    intro += ['\n## Field reference\n', *links]
    # Include all remaining front matter so generation does not lose unknown keys.
    front = {k: v for k, v in spec.items() if k != 'sections'}
    intro += ['\n## Source front matter\n', '```yaml\n' + yaml.safe_dump(
        front, sort_keys=False, allow_unicode=True, width=90) + '```\n']
    pages['technical/index.md'] = '\n'.join(intro).replace('](source/', '](../source/').replace('](fields/', '](../fields/')
    pages['index.md'] = home_page(spec)
    if any(s['id'] == 'metadata' for s in spec['sections']):
        notes = Path(__file__).resolve().parents[1] / 'notes'
        pages['history/reconciliation.md'] = (
            '<!-- Generated from notes/version-history-reconciliation.md. -->\n\n' +
            (notes / 'version-history-reconciliation.md').read_text(encoding='utf-8'))
        pages['history/archive/version-history-original.txt'] = (
            notes / 'archive/version-history-original.txt').read_text(encoding='utf-8')
    pages['guidance/source-field-completeness.md'] = (
        '<!-- Generated from notes/source-field-completeness.md. -->\n\n' +
        (Path(__file__).resolve().parents[1] / 'notes/source-field-completeness.md').read_text(encoding='utf-8'))
    pages['guidance/legacy-storage-enums.md'] = (
        '<!-- Generated from notes/legacy-storage-enums.md. -->\n\n' +
        (Path(__file__).resolve().parents[1] / 'notes/legacy-storage-enums.md').read_text(encoding='utf-8'))
    pages['guidance/reference-data.md'] = (
        '<!-- Generated from notes/reference-data-policy.md. -->\n\n' +
        (Path(__file__).resolve().parents[1] / 'notes/reference-data-policy.md').read_text(encoding='utf-8'))
    pages['guides/index.html'] = guide_index(spec)
    for section_id in (section['id'] for section in spec['sections']):
        prototype = guide(spec, display, section_id)
        if prototype is not None:
            pages[f'guides/{section_id}.html'] = prototype
    pages['source/hay-spec.yaml'] = source
    pages['source/hay-spec.json'] = transcription
    return pages


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=Path('src/hay-spec.yaml'))
    parser.add_argument('--output', type=Path, default=Path('docs'))
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--display', type=Path, default=Path('reference-display.yaml'))
    args = parser.parse_args()
    try:
        display = load_spec(args.display.read_text(encoding='utf-8'))
        pages = outputs(args.source.read_text(encoding='utf-8'), display)
        stale = []
        for name, text in pages.items():
            path = args.output / name
            if args.check:
                if not path.exists() or path.read_text(encoding='utf-8') != text:
                    stale.append(name)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding='utf-8')
        for directory, pattern in (('fields', '*.md'), ('guides', '*.html')):
            for path in (args.output / directory).glob(pattern):
                if path.relative_to(args.output).as_posix() not in pages:
                    stale.append(path.relative_to(args.output).as_posix())
        if stale:
            print('Stale or unexpected generated pages: ' + ', '.join(stale), file=sys.stderr)
            return 1
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f'Documentation generation failed: {exc}', file=sys.stderr)
        return 1
    print(f'{len(pages)} generated files ' + ('verified.' if args.check else 'written.'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
